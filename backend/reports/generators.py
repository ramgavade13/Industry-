def build_risk_pdf():
    buffer = BytesIO()
    p = canvas.Canvas(buffer, pagesize=A4)
    add_header(p, "Risk Report")

    y = 750
    p.setFont("Helvetica", 10)
    for r in RiskAlert.objects.all():
        p.drawString(50, y, f"{r.project}")
        y -= 15
        p.setFillColorRGB(0.47, 0.47, 0.47)
        p.drawString(50, y, f"{r.risk} — Severity: {r.severity.upper()}")
        p.setFillColorRGB(0, 0, 0)
        y -= 22

    y -= 10
    p.setFont("Helvetica-Bold", 12)
    p.drawString(40, y, "Team Productivity Snapshot")
    y -= 20
    p.setFont("Helvetica", 10)
    for pr in TeamProductivity.objects.all():
        p.drawString(50, y, f"{pr.team}: {pr.completed}% completed, {pr.pending}% pending")
        y -= 16

    add_footer(p)
    p.showPage()
    p.save()
    buffer.seek(0)
    return buffer