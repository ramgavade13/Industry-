"""
Word (.docx) versions of the management reports. They show the same data as the
PDF reports in generators.py, as proper tables.

Needs the python-docx package (pip install python-docx).
"""

from datetime import datetime
from io import BytesIO

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

from finance.kpi_cards import kpi_cards
from finance.models import RevenueMonth
from productivity.models import TeamProductivity
from risk.models import RiskAlert

GOLD = RGBColor(0xC9, 0xA2, 0x27)
GREY = RGBColor(0x77, 0x77, 0x77)
HEADER_FILL = "0F1420"
RISK_WIDTHS = [1.6, 0.9, 0.7, 3.3]  # inches: Project, Severity, Score, Why


def _shade(cell, hex_fill):
    properties = cell._tc.get_or_add_tcPr()
    shading = OxmlElement("w:shd")
    shading.set(qn("w:val"), "clear")
    shading.set(qn("w:color"), "auto")
    shading.set(qn("w:fill"), hex_fill)
    properties.append(shading)


def _new_document(title):
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(10.5)

    brand = doc.add_paragraph()
    run = brand.add_run("INDUSTRY — AI Executive Decision Agent")
    run.bold = True
    run.font.size = Pt(10)
    run.font.color.rgb = GOLD

    doc.add_heading(title, level=0)

    stamp = doc.add_paragraph()
    run = stamp.add_run(f"Generated on {datetime.now():%d %b %Y, %H:%M}")
    run.font.size = Pt(9)
    run.font.color.rgb = GREY

    footer = doc.sections[0].footer.paragraphs[0]
    run = footer.add_run("Generated by AI Executive Decision Agent")
    run.font.size = Pt(8)
    run.font.color.rgb = GREY
    return doc


def _table(doc, headers, rows, empty_text="No data available.", widths=None):
    if not rows:
        note = doc.add_paragraph(empty_text)
        note.runs[0].italic = True
        return

    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    for cell, text in zip(table.rows[0].cells, headers):
        cell.text = ""
        run = cell.paragraphs[0].add_run(text)
        run.bold = True
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        _shade(cell, HEADER_FILL)

    for row in rows:
        cells = table.add_row().cells
        for cell, text in zip(cells, row):
            cell.text = str(text)

    if widths:
        table.autofit = False
        for column, width in zip(table.columns, widths):
            column.width = Inches(width)
        for row in table.rows:
            for cell, width in zip(row.cells, widths):
                cell.width = Inches(width)


def _save(doc):
    buffer = BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer


def _kpi_rows():
    return [(k.label, k.value, k.change or "-") for k in kpi_cards()]


def _risk_rows():
    return [
        (r.project, r.severity.upper(), "-" if r.score is None else r.score, r.risk)
        for r in RiskAlert.objects.all().order_by("-score")
    ]


def build_executive_docx():
    doc = _new_document("Executive Summary Report")
    doc.add_heading("Key Performance Indicators", level=1)
    _table(doc, ["KPI", "Value", "Change"], _kpi_rows())
    doc.add_heading("Risk Alerts", level=1)
    _table(doc, ["Project", "Severity", "Score", "Why"], _risk_rows(), "No risk alerts right now.", RISK_WIDTHS)
    return _save(doc)


def build_kpi_docx():
    doc = _new_document("KPI Report")
    _table(doc, ["KPI", "Value", "Change"], _kpi_rows())
    return _save(doc)


def build_financial_docx():
    doc = _new_document("Financial Report")
    months = list(RevenueMonth.objects.order_by("id"))

    rows = [
        (m.month, f"{m.revenue:.1f}", f"{m.expenses:.1f}", f"{m.revenue - m.expenses:.1f}")
        for m in months
    ]
    if months:
        revenue = sum(m.revenue for m in months)
        expenses = sum(m.expenses for m in months)
        rows.append(("Total", f"{revenue:.1f}", f"{expenses:.1f}", f"{revenue - expenses:.1f}"))

    note = doc.add_paragraph("All amounts in ₹ lakhs.")
    note.runs[0].font.size = Pt(9)
    note.runs[0].font.color.rgb = GREY
    _table(doc, ["Month", "Revenue", "Expenses", "Profit"], rows)
    return _save(doc)


def build_risk_docx():
    doc = _new_document("Risk Report")
    doc.add_heading("Project Risks", level=1)
    _table(doc, ["Project", "Severity", "Score", "Why"], _risk_rows(), "No risk alerts right now.", RISK_WIDTHS)

    doc.add_heading("Team Productivity Snapshot", level=1)
    rows = [
        (t.team, t.completed, t.pending, f"{round(t.completed / (t.completed + t.pending) * 100)}%"
         if (t.completed + t.pending) else "-")
        for t in TeamProductivity.objects.all()
    ]
    _table(doc, ["Team", "Tasks completed", "Tasks pending", "Completion"], rows)
    return _save(doc)